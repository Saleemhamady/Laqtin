// Cloudflare Stream: video hosting with adaptive streaming from Cloudflare's network
// (including its Beirut data center).
//
// Teachers upload straight from their browser to Cloudflare ("direct creator
// uploads"), so big files never pass through this server or the 100 MB proxy limit.
// Students get HLS playback that adapts to their connection.
import { config } from './config.js';

let fetchImpl = (...a) => fetch(...a);
/** Tests swap in a fake Cloudflare API. */
export function setStreamFetch(fn) {
  fetchImpl = fn;
}

export const streamEnabled = () => Boolean(config.cloudflare.accountId && config.cloudflare.apiToken);

async function api(path, { method = 'GET', json, body } = {}) {
  const url = `https://api.cloudflare.com/client/v4/accounts/${config.cloudflare.accountId}/stream${path}`;
  const headers = { Authorization: `Bearer ${config.cloudflare.apiToken}` };
  if (json) headers['Content-Type'] = 'application/json';
  const res = await fetchImpl(url, { method, headers, body: json ? JSON.stringify(json) : body });
  const data = await res.json().catch(() => ({}));
  if (!res.ok || data.success === false) {
    const msg = data.errors?.[0]?.message || res.statusText || 'request failed';
    const err = new Error(`Cloudflare Stream: ${msg}`);
    err.expose = true;
    err.status = 502;
    throw err;
  }
  return data.result;
}

/** One-time URL the teacher's browser uploads the file to (basic uploads: up to 200 MB). */
export async function createDirectUpload({ name, maxDurationSeconds = 3 * 3600 }) {
  const r = await api('/direct_upload', { method: 'POST', json: { maxDurationSeconds, meta: { name: String(name).slice(0, 200) } } });
  return { uid: r.uid, uploadURL: r.uploadURL };
}

/** Normalised status of a video. */
export async function getVideo(uid) {
  const v = await api(`/${encodeURIComponent(uid)}`);
  const state = v.readyToStream ? 'ready' : v.status?.state === 'error' ? 'error' : v.status?.state === 'pendingupload' ? 'uploading' : 'processing';
  return {
    uid: v.uid,
    state,
    pct: Number(v.status?.pctComplete) || 0,
    error: v.status?.errorReasonText || null,
    hls: v.playback?.hls || null,
    thumbnail: v.thumbnail || null,
    duration: v.duration > 0 ? v.duration : null,
  };
}

export async function deleteVideo(uid) {
  if (!uid) return;
  await api(`/${encodeURIComponent(uid)}`, { method: 'DELETE' }).catch((err) => console.warn('[stream] delete failed', uid, err.message));
}

export async function listCaptions(uid) {
  const r = await api(`/${encodeURIComponent(uid)}/captions`);
  return (r || []).map((c) => ({ language: c.language, label: c.label, generated: Boolean(c.generated), status: c.status || 'ready' }));
}

/** Automatic subtitles generated by Cloudflare from the audio. */
export function generateCaptions(uid, lang) {
  return api(`/${encodeURIComponent(uid)}/captions/${encodeURIComponent(lang)}/generate`, { method: 'POST' });
}

/** Teacher-provided WebVTT subtitles. */
export function uploadCaptions(uid, lang, vttBuffer) {
  const fd = new FormData();
  fd.append('file', new Blob([vttBuffer], { type: 'text/vtt' }), `${lang}.vtt`);
  return api(`/${encodeURIComponent(uid)}/captions/${encodeURIComponent(lang)}`, { method: 'PUT', body: fd });
}

export function deleteCaptions(uid, lang) {
  return api(`/${encodeURIComponent(uid)}/captions/${encodeURIComponent(lang)}`, { method: 'DELETE' });
}
